// scripts/deploy.js
// ============================================================
//  Deploy Script — runs with:
//    npx hardhat run scripts/deploy.js --network localhost
//    npx hardhat run scripts/deploy.js --network sepolia
// ============================================================

const { ethers } = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("\n========================================");
  console.log("  Deploying LandRegistry Contract...");
  console.log("========================================\n");

  // Get the list of accounts from Hardhat.
  // On localhost: these are the 20 pre-funded test accounts.
  // On testnet: this is the account from your DEPLOYER_PRIVATE_KEY in .env
  const [deployer] = await ethers.getSigners();

  console.log("Deployer address :", deployer.address);
  console.log(
    "Deployer balance :",
    ethers.formatEther(await ethers.provider.getBalance(deployer.address)),
    "ETH\n"
  );

  // On localhost, advance nonce so the contract address is NOT the default 0x5FbDB... 
  // (which is globally blacklisted by Blockaid/MetaMask security alerts).
  const network = await ethers.provider.getNetwork();
  if (network.chainId === 31337n || network.chainId === 1337n) {
    const currentNonce = await ethers.provider.getTransactionCount(deployer.address);
    if (currentNonce === 0) {
      console.log("Advancing nonce to generate an unflagged, fresh contract address...");
      const dummyTx = await deployer.sendTransaction({
        to: deployer.address,
        value: 0,
      });
      await dummyTx.wait(1);
    }
  }

  // Compile and get the contract factory
  // A "factory" is an object that knows how to deploy a contract
  const LandRegistry = await ethers.getContractFactory("LandRegistry");

  // Deploy the contract, passing the deployer's address as the initialAdmin
  // The constructor will grant DEFAULT_ADMIN_ROLE and REGISTRAR_ROLE to this address
  console.log("Deploying contract...");
  const landRegistry = await LandRegistry.deploy(deployer.address);

  // Wait for the deployment transaction to be mined
  await landRegistry.waitForDeployment();

  const contractAddress = await landRegistry.getAddress();

  console.log("\n✅ LandRegistry deployed successfully!");
  console.log("   Contract address:", contractAddress);
  console.log("   Network         :", (await ethers.provider.getNetwork()).name);

  // ============================================================
  //  Save deployment info to a JSON file.
  //  The backend and frontend will read this file to know
  //  which address to talk to.
  // ============================================================
  const deploymentInfo = {
    contractAddress,
    deployerAddress: deployer.address,
    network: (await ethers.provider.getNetwork()).name,
    chainId: (await ethers.provider.getNetwork()).chainId.toString(),
    deployedAt: new Date().toISOString(),
    blockNumber: await ethers.provider.getBlockNumber(),
  };

  // Write to contracts folder (for reference)
  const deploymentsDir = path.join(__dirname, "../deployments");
  if (!fs.existsSync(deploymentsDir)) {
    fs.mkdirSync(deploymentsDir, { recursive: true });
  }

  const networkName = deploymentInfo.network === "unknown" ? "localhost" : deploymentInfo.network;
  fs.writeFileSync(
    path.join(deploymentsDir, `${networkName}.json`),
    JSON.stringify(deploymentInfo, null, 2)
  );
  console.log(`\n📄 Deployment info saved to deployments/${networkName}.json`);

  // ============================================================
  //  Copy the ABI to the backend and frontend.
  //  The ABI (Application Binary Interface) tells ethers.js how
  //  to call the contract functions. It is generated by Hardhat
  //  when you run "npx hardhat compile".
  // ============================================================
  const artifactPath = path.join(
    __dirname,
    "../artifacts/contracts/LandRegistry.sol/LandRegistry.json"
  );

  if (fs.existsSync(artifactPath)) {
    const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
    const abiOutput = {
      contractAddress,
      abi: artifact.abi,
    };

    // Copy to backend
    const backendPath = path.join(
      __dirname,
      "../../backend/config/LandRegistry.json"
    );
    fs.mkdirSync(path.dirname(backendPath), { recursive: true });
    fs.writeFileSync(backendPath, JSON.stringify(abiOutput, null, 2));
    console.log("📄 ABI copied to backend/config/LandRegistry.json");

    // Copy to frontend
    const frontendPath = path.join(
      __dirname,
      "../../frontend/src/contracts/LandRegistry.json"
    );
    fs.mkdirSync(path.dirname(frontendPath), { recursive: true });
    fs.writeFileSync(frontendPath, JSON.stringify(abiOutput, null, 2));
    // Update backend/.env CONTRACT_ADDRESS
    const backendEnvPath = path.join(__dirname, "../../backend/.env");
    if (fs.existsSync(backendEnvPath)) {
      let envContent = fs.readFileSync(backendEnvPath, "utf8");
      envContent = envContent.replace(
        /CONTRACT_ADDRESS=.*/,
        `CONTRACT_ADDRESS=${contractAddress}`
      );
      fs.writeFileSync(backendEnvPath, envContent);
      console.log("📄 backend/.env CONTRACT_ADDRESS updated!");
    }
  }

  console.log("\n========================================");
  console.log("  Next Step: Run setup-roles.js to");
  console.log("  assign registrar roles to admin wallets");
  console.log("  npx hardhat run scripts/setup-roles.js --network localhost");
  console.log("========================================\n");
}

// Standard Hardhat boilerplate — run main() and handle errors
main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("\n❌ Deployment failed:", error);
    process.exit(1);
  });

